  @classmethod
  def get_presets(cls):
    """Returns a list of valid preset names without 'Text' suffix."""
    return [
      attr[:-4].lower()
        for attr in dir(cls) 
        if attr.endswith("Text") and not attr.startswith("__")
    ]
  
